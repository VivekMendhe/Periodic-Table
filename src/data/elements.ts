/**
 * Development-time validation function for the element dataset
 * Asserts 118 unique elements, unbroken 1-118 sequence, and valid periods/groups.
 */
export function validateElements(data: ElementData[]): { isValid: boolean; errors: string[] } {
  const errors: string[] = [];
  if (data.length !== 118) {
    errors.push(`Expected 118 elements, received ${data.length}`);
  }

  const seenNumbers = new Set<number>();
  const seenSymbols = new Set<string>();

  data.forEach((el, index) => {
    const expected = index + 1;
    if (el.atomicNumber !== expected) {
      errors.push(`Element ${el.symbol} at index ${index} has atomicNumber ${el.atomicNumber}, expected ${expected}`);
    }
    if (seenNumbers.has(el.atomicNumber)) {
      errors.push(`Duplicate atomic number: ${el.atomicNumber}`);
    }
    seenNumbers.add(el.atomicNumber);

    if (seenSymbols.has(el.symbol)) {
      errors.push(`Duplicate symbol: ${el.symbol}`);
    }
    seenSymbols.add(el.symbol);

    if (el.period < 1 || el.period > 7) {
      errors.push(`Element ${el.symbol} has invalid period ${el.period}`);
    }

    if (el.group !== null && (el.group < 1 || el.group > 18)) {
      errors.push(`Element ${el.symbol} has invalid group ${el.group}`);
    }
  });

  return {
    isValid: errors.length === 0,
    errors,
  };
}
